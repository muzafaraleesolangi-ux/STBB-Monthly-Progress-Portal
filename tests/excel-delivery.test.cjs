'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('index.html','utf8');
const editor=fs.readFileSync('MPR_Online_Editor.html','utf8');
const studio=fs.readFileSync('studio-core-v2.js','utf8');
const android=fs.readFileSync('android-app/app/src/main/java/pk/edu/stbbprogress/MainActivity.java','utf8');
assert.ok(html.includes('excel-download-v2.js'),'Browser and Android share the Excel delivery helper');
assert.ok(html.includes('const studioMonth='),'Export uses authoritative Studio month');
assert.ok(html.includes("await request('export'"),'Cloud export is attempted before device download');
assert.ok(html.includes('await Promise.allSettled([loadHistory(),refreshSchool()])'),'History refresh happens immediately on archival');
assert.ok(html.includes('MPRDownloads.saveExcel'),'History and new exports use one download handler');
assert.ok(studio.includes('autoExport:true'),'Submitted studio initiates actual Excel generation');
assert.ok(!studio.slice(studio.indexOf('async function review()'),studio.indexOf('function findBook(')).includes("request('save-draft'"),'Submitted workflow must never resave a Draft');
assert.ok(editor.includes("e.data.autoExport===true"),'Editor respects automated export after Hydrate');
assert.ok(android.includes('class ExcelSaveBridge'),'Android implements native Save Document bridge');
assert.ok(android.includes('@JavascriptInterface'),'Native bridge callable after Cloud archival');
const dom=new JSDOM('<!DOCTYPE html><html><body></body></html>',{url:'https://portal.test/',runScripts:'outside-only'});
const w=dom.window;w.atob=b64=>Buffer.from(b64,'base64').toString('binary');
const calls=[];w.STBBAndroid={saveExcel:(b64,file)=>calls.push({b64,file})};
w.eval(fs.readFileSync('excel-download-v2.js','utf8'));
const data=Buffer.concat([Buffer.from([0x50,0x4b,0x03,0x04]),Buffer.alloc(200)]);
const b64=data.toString('base64');
let result=w.MPRDownloads.saveExcel(b64,'October 2026');
assert.equal(result.mode,'android');
assert.equal(calls.length,1);
assert.equal(calls[0].file,'October 2026.xlsx');
assert.equal(calls[0].b64,b64);
delete w.STBBAndroid;
let created=null,clicked=0;w.URL.createObjectURL=blob=>{created=blob;return 'blob:https://portal.test/excel'};
w.URL.revokeObjectURL=()=>{};
w.HTMLAnchorElement.prototype.click=function(){clicked++};
result=w.MPRDownloads.saveExcel(b64,'October 2026.xlsx');
assert.equal(result.mode,'browser');
assert.ok(created instanceof w.Blob);
assert.equal(created.size,data.length);
assert.equal(clicked,1,'Browser download should be attempted automatically');
const fallback=w.document.querySelector('#mprDownloadHint a[download]');
assert.ok(fallback,'If mobile browser blocks auto download, a visible retry link must exist');
assert.equal(fallback.download,'October 2026.xlsx');
assert.throws(()=>w.MPRDownloads.saveExcel('INVALID','bad.xlsx'),/invalid/i,'Malformed file is rejected');
dom.window.close();
console.log('PASS: submitted month -> cloud archive -> native Android Save dialog or visible browser download; ZIP validation and History support');
